import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const env = process.env;
const supabaseUrl = env.NEXT_PUBLIC_SUPABASE_URL || env.SUPABASE_URL || "";
const supabaseAnonKey =
  env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ||
  env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  env.SUPABASE_PUBLISHABLE_KEY ||
  env.SUPABASE_ANON_KEY ||
  "";
// Only set in v0 previews, where email links must go through the v0 redirect proxy.
const redirectUrl = env.NEXT_PUBLIC_DEV_SUPABASE_REDIRECT_URL || "";

const config = { supabaseUrl, supabaseAnonKey, redirectUrl };
const out = fileURLToPath(new URL("../ack-config.js", import.meta.url));

writeFileSync(
  out,
  "/* Generated by scripts/write-auth-config.mjs. Public Supabase settings only; access is enforced by Supabase. */\n" +
    "window.ACK_AUTH = " + JSON.stringify(config, null, 2) + ";\n",
);

console.log(supabaseUrl && supabaseAnonKey ? "Sign-in enabled." : "Supabase settings missing: sign-in disabled.");
